import {test,expect} from '@playwright/test';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
const url=new URL('../../../../docs/zynthian-control-mapping.html',import.meta.url).href;
const evidence=process.env.MAPPING_EVIDENCE || '/tmp/crest-control-mapping-tests';
const draft=page=>page.evaluate(()=>JSON.parse(localStorage.getItem('crest-zynthian-control-workbook-v1')));
test.beforeEach(async({page})=>{await page.goto(url);await expect(page.locator('#controls article')).toHaveCount(25);});

test('control worksheet: edit, export, restore and import without losing intent',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.locator('#project summary').click();
  await page.getByLabel('Bundle name',{exact:true}).fill('My control decisions');
  await page.getByLabel('Controller / hardware',{exact:true}).fill('Steam Deck + keyboard');
  const press='Select a clip without playing it.\nSecond action should launch it.';
  await page.getByLabel('A / South — Press / primary gesture',{exact:true}).fill(press);
  const row=page.locator('[data-control="pad:a"]');
  await row.locator('summary').click();
  await page.getByLabel('A / South — Hold / long press',{exact:true}).fill('Preview only while held.');
  await page.getByLabel('A / South — Modifiers / combinations',{exact:true}).fill('LB + A: open clip settings.');
  await page.getByRole('button',{name:'Piano roll',exact:true}).click();
  await page.locator('#screen-rules summary').click();
  await page.getByLabel('Rules for this screen',{exact:true}).fill('Keep cursor position when opening the popover.');
  await page.getByLabel('Decision for pad:b',{exact:true}).selectOption('disable');
  await page.locator('#new-control').locator('..').locator('summary').click();
  await page.locator('#new-control input').fill('L4 + touchpad');
  await page.getByRole('button',{name:'Add control',exact:true}).click();
  await page.getByLabel('L4 + touchpad — Press / primary gesture',{exact:true}).fill('Custom behavior: <script>alert("text only")</script>');
  await page.locator('#new-context').locator('..').locator('summary').click();
  await page.locator('#new-context input').fill('Piano roll · block mode');
  await page.getByRole('button',{name:'Add mode',exact:true}).click();
  await page.getByLabel('Rules for this screen',{exact:true}).fill('Empty cells sustain; OFF releases.');
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Save JSON bundle ↓',exact:true}).click();
  const download=await downloading;
  const exported=JSON.parse(await readFile(await download.path(),'utf8'));
  expect(exported.reference.controls).toHaveLength(62);expect(exported.reference.contexts).toHaveLength(52);
  expect(exported.assignments.find(item=>item.context==='global'&&item.control==='pad:a').press).toBe(press);
  expect(exported.assignments.find(item=>item.context==='pattern_editor'&&item.control==='pad:b').decision).toBe('disable');
  expect(exported.customControls[0].label).toBe('L4 + touchpad');
  await page.reload();expect(await draft(page)).toEqual(exported);
  await page.getByRole('button',{name:'Start a new blank bundle',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();expect(await draft(page)).toEqual(exported);
  await page.getByRole('button',{name:'Start a new blank bundle',exact:true}).click();
  await page.getByRole('button',{name:'Replace draft',exact:true}).click();expect((await draft(page)).assignments).toEqual([]);
  await page.locator('#file').setInputFiles({name:'decisions.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await page.getByRole('button',{name:'Replace draft',exact:true}).click();
  const imported=await draft(page);
  expect({...imported,updatedAt:exported.updatedAt}).toEqual(exported);
  await page.getByRole('button',{name:'Review all decisions',exact:true}).click();
  await expect(page.locator('#review-content')).toContainText('LB + A: open clip settings.');
  await expect(page.locator('#review-content')).toContainText('<script>alert("text only")</script>');
  expect(errors).toEqual([]);
  await mkdir(evidence,{recursive:true});
  await writeFile(evidence+'/roundtrip.json',JSON.stringify(exported,null,2));
});

test('control worksheet: invalid imports and unavailable storage preserve edits',async({page})=>{
  await page.getByLabel('A / South — Press / primary gesture',{exact:true}).fill('Keep this decision.');
  const before=await draft(page);
  await page.locator('#file').setInputFiles({name:'wrong.json',mimeType:'application/json',buffer:Buffer.from('{"schemaVersion":99}')});
  await expect(page.locator('#notice')).toContainText('Your current draft was kept');
  expect(await draft(page)).toEqual(before);
  await page.evaluate(()=>localStorage.setItem('crest-zynthian-control-workbook-v1','broken original data'));
  await page.reload();await expect(page.locator('#notice')).toContainText('left untouched');
  await page.getByLabel('A / South — Press / primary gesture',{exact:true}).fill('Session-only decision.');
  expect(await page.evaluate(()=>localStorage.getItem('crest-zynthian-control-workbook-v1'))).toBe('broken original data');
  const downloading=page.waitForEvent('download');await page.locator('#save').click();
  const output=JSON.parse(await readFile(await (await downloading).path(),'utf8'));
  expect(output.assignments[0].press).toBe('Session-only decision.');
});

