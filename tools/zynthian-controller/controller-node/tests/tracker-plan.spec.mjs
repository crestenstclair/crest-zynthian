test('shared runtime input moves focus, preserves modal return, and ignores an unfocused controller',async({page})=>{
  await page.addInitScript(()=>{
    window.pad={id:'Test Pro Controller',index:0,mapping:'standard',buttons:Array.from({length:16},()=>({pressed:false,value:0})),axes:[0,0,0,0]};
    Object.defineProperty(navigator,'getGamepads',{value:()=>[window.pad]});
  });
  await page.reload();
  await page.locator('#song-0-0').focus();
  await expect(page.locator('#input-status')).toHaveText('Test Pro Controller');
  await page.evaluate(()=>{window.pad.buttons[13].pressed=true;});
  await expect(page.locator('#song-1-0')).toBeFocused();
  await page.evaluate(()=>{window.pad.buttons[13].pressed=false;});
  await page.keyboard.press('F5');
  await expect(page.locator('#popover')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('#song-1-0')).toBeFocused();
  await page.evaluate(()=>{window.pad.buttons[0].pressed=true;});
  await expect(page.locator('#identity')).toContainText('PHRASE 01');
  await page.evaluate(()=>{window.pad.buttons[0].pressed=false;});
  await page.keyboard.press('Escape');
  await expect(page.locator('#song-1-0')).toBeFocused();
  await page.evaluate(()=>{Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>false});window.pad.buttons[13].pressed=true;});
  await expect(page.locator('#input-status')).toContainText('click this window');
  await expect(page.locator('#song-1-0')).toBeFocused();
});
