test('shared edits, sustain/OFF, unique copies and undo stay coherent across views',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.locator('#song-0-0').click();
  await mkdir(evidence,{recursive:true});
  await page.screenshot({path:evidence+'/tracker.png'});
  await page.locator('#note-2').click();
  await expect(page.getByRole('heading',{name:'This phrase is shared'})).toBeVisible();
  await page.getByRole('button',{name:'Edit shared',exact:true}).click();
  await page.getByLabel('Note',{exact:true}).selectOption('EMPTY');
  await page.getByRole('button',{name:'Apply demo edit'}).click();
  await expect(page.locator('#note-2')).toHaveText('—');
  await page.getByRole('button',{name:'PIANO ROLL',exact:true}).click();
  await expect(page.locator('#note-0')).toHaveAttribute('aria-label',/length 4/);
  await page.screenshot({path:evidence+'/piano.png'});
  await page.getByRole('button',{name:'← SONG',exact:true}).click();
  await expect(page.locator('#song-0-0')).toBeFocused();
  await page.locator('#song-1-0').click();
  await expect(page.locator('#note-0')).toHaveAttribute('aria-label',/length 4/);
  await page.locator('#note-0').click();
  await page.getByRole('button',{name:'Make unique',exact:true}).click();
  await page.getByLabel('Note',{exact:true}).selectOption('C5');
  await page.getByLabel('MIDI Channel',{exact:true}).selectOption('3');
  await page.getByLabel('Velocity',{exact:true}).fill('127');
  await page.getByRole('button',{name:'Apply demo edit'}).click();
  await expect(page.locator('#identity')).toContainText('PHRASE 24');
  await expect(page.locator('#note-0')).toHaveAttribute('aria-label',/C5.*channel 3/);
  await page.getByRole('button',{name:'UNDO',exact:true}).click();
  await expect(page.locator('#note-0')).toHaveText('C4');
  await page.getByRole('button',{name:'REDO',exact:true}).click();
  await expect(page.locator('#note-0')).toHaveText('C5');
  await page.getByRole('button',{name:'← SONG',exact:true}).click();
  await expect(page.locator('#song-1-0')).toHaveText('24');
  await expect(page.locator('#song-0-0')).toHaveText('01');
  await page.locator('#song-0-0').click();
  await expect(page.locator('#note-0')).toHaveText('C4');
  await page.getByRole('button',{name:'TRACKER',exact:true}).click();
  await expect(page.locator('#note-14')).toHaveText('OFF');
  expect(errors).toEqual([]);
});

