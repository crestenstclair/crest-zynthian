import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
const url=new URL('../../../../docs/crest-tracker-zynthian-plan.html',import.meta.url).href;
const evidence=process.env.TRACKER_PLAN_EVIDENCE || '/tmp/crest-tracker-plan-tests';
