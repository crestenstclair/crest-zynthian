import {test,expect} from '@playwright/test';
import {connect,ready,state,choose,navigation,loadSnapshot,capture} from './live-helpers.mjs';
test.beforeEach(async({page})=>connect(page));
async function holdCross(page,direction) {
  await page.keyboard.down('x');await page.keyboard.press(direction);await ready(page);await page.keyboard.up('x');await ready(page);
}
async function openPhrase(page) {
  await navigation(page,'launcher');
  await page.locator('.clip[aria-label*="FluidSynth"]').first().click();await ready(page);
  await page.getByRole('button',{name:'Tracker',exact:true}).click();
}
const firstNote=(page,field)=>page.getByRole('button',{name:new RegExp('step 1, '+field+',')}).first();

test('Crest controls: single-track edits, held modifiers and escape paths',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await loadSnapshot(page);await openPhrase(page);
  await expect(page.locator('.tracker-cell.selected')).toBeVisible();
  await firstNote(page,'pitch').click();await ready(page);
  const before=(await state(page)).sequence.events;
  const pitch=before.find(e=>e.step===0).note;
  await holdCross(page,'ArrowRight');
  let after=(await state(page)).sequence.events;
  expect(after).toHaveLength(before.length);expect(after.find(e=>e.step===0).note).toBe(pitch+1);
  await page.keyboard.press('Enter');await ready(page);
  expect((await state(page)).sequence.events).toEqual(after); // Select does not toggle an existing note.
  await page.keyboard.press('ArrowRight');
  expect((await state(page)).trackerField).toBe(1);
  const velocity=after.find(e=>e.step===0).velocity;
  await holdCross(page,'ArrowUp');
  expect((await state(page)).sequence.events.find(e=>e.step===0).velocity).toBe(velocity+10);
  await firstNote(page,'pitch').click();await ready(page);
  const length=(await state(page)).sequence.events.find(e=>e.step===0).duration;
  await page.keyboard.press(']');await ready(page);
  expect((await state(page)).sequence.events.find(e=>e.step===0).duration).toBeCloseTo(length+1,2);
  await page.getByRole('button',{name:'☰ Menu',exact:true}).click();await choose(page,'Undo');
  expect((await state(page)).sequence.events.find(e=>e.step===0).duration).toBeCloseTo(length,2);
  await page.getByRole('button',{name:'☰ Menu',exact:true}).click();await choose(page,'Redo');
  expect((await state(page)).sequence.events.find(e=>e.step===0).duration).toBeCloseTo(length+1,2);
  // Pointer-selected empty cell must accept Cross/Enter, not re-click itself.
  await page.getByRole('button',{name:'Instrument, step 4, pitch, empty',exact:true}).click();await ready(page);
  const noteCount=(await state(page)).sequence.events.length;
  await page.keyboard.press('Enter');await ready(page);
  expect((await state(page)).sequence.events).toHaveLength(noteCount+1);
  const inserted=(await state(page)).sequence.events.find(e=>e.step===3);
  await holdCross(page,'ArrowUp');
  expect((await state(page)).sequence.events.find(e=>e.step===3).note).toBe(inserted.note+12);
  await page.getByRole('button',{name:'+ Small',exact:true}).click();await ready(page);
  expect((await state(page)).sequence.events.find(e=>e.step===3).note).toBe(inserted.note+13);
  await page.getByRole('button',{name:'Clear cell',exact:true}).click();await ready(page);
  expect((await state(page)).sequence.events).toHaveLength(noteCount);
  await page.getByRole('button',{name:'☰ Menu',exact:true}).click();await choose(page,'Undo');
  expect((await state(page)).sequence.events.find(e=>e.step===3).note).toBe(inserted.note+13);
  await capture(page,'controls-01-editable-phrase');
  await page.keyboard.press('Shift+ArrowUp');await ready(page);
  expect((await state(page)).properties).toBe(true);
  expect((await state(page)).screen).toBe('pattern_editor');
  await choose(page,'Length (beats)');await ready(page);
  expect((await state(page)).inlineEditor).not.toBe(true);
  expect((await state(page)).items[(await state(page)).selected].id).toBe('property:length');
  await holdCross(page,'ArrowRight');
  await page.keyboard.press('Shift+ArrowDown');await ready(page);
  expect((await state(page)).screen).toBe('pattern_editor');
  expect((await state(page)).inlineEditor).not.toBe(true);
  expect((await state(page)).detailWorkspace).toBeNull();
  expect((await state(page)).canvasFocus).toBe(true);
  await page.keyboard.press('y');await expect(page.locator('#navigation-panel')).toBeVisible();
  await page.keyboard.press('Escape');await expect(page.locator('#navigation-panel')).not.toBeVisible();
  await page.keyboard.press('Shift+ArrowLeft');await ready(page);expect((await state(page)).screen).toBe('launcher');
  await page.keyboard.press('Shift+ArrowLeft');await expect(page.locator('#home-view')).toBeVisible();
  await expect(page.locator('#sequence')).not.toBeVisible();
  await capture(page,'controls-02-workspaces');
  await page.locator('#home-view').getByRole('button',{name:/^Instruments/}).click();await ready(page);
  await choose(page,'+ Add instrument');expect((await state(page)).screen).toBe('engine');
  await page.keyboard.press('Shift+ArrowLeft');await ready(page);expect((await state(page)).screen).toBe('chain_manager');
  await choose(page,'FluidSynth');
  await page.keyboard.press('Shift+ArrowUp');await ready(page);
  expect((await state(page)).detailWorkspace).toBe('chain_control');
  await page.keyboard.press('Shift+ArrowDown');await ready(page);
  expect((await state(page)).screen).toBe('chain_control');
  expect((await state(page)).detailWorkspace).toBeNull();
  await navigation(page,'snapshots');await choose(page,'Save as new snapshot');
  await expect(page.locator('#name-entry')).toBeVisible();
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('never saved');
  await page.keyboard.press('Shift+ArrowLeft');await ready(page);
  expect((await state(page)).screen).not.toBe('keyboard');
  await page.keyboard.press('Home');await expect(page.locator('#home-view')).toBeVisible();
  expect(errors).toEqual([]);
});

