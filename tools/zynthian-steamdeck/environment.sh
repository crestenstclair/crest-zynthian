#!/bin/bash
# Standard Zynthian Oram configuration for a desktop audio session.
export ZYNTHIAN_DIR="${ZYNTHIAN_DIR:-/opt/zynthian}"
export LD_LIBRARY_PATH="$ZYNTHIAN_DIR/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export ZYNTHIAN_UI_DIR="$ZYNTHIAN_DIR/zynthian-ui"
export ZYNTHIAN_SYS_DIR="$ZYNTHIAN_DIR/zynthian-sys"
export ZYNTHIAN_DATA_DIR="$ZYNTHIAN_DIR/zynthian-data"
export ZYNTHIAN_CONFIG_DIR="${ZYNTHIAN_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/zynthian}"
export ZYNTHIAN_MY_DATA_DIR="${ZYNTHIAN_MY_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/zynthian}"
export ZYNTHIAN_EX_DATA_DIR="${ZYNTHIAN_EX_DATA_DIR:-/run/media/$USER}"
export ZYNTHIAN_PLUGINS_DIR="$ZYNTHIAN_DIR/plugins"
export ZYNTHIAN_SW_DIR="$ZYNTHIAN_DIR/sw"
export PYTHONPATH="$ZYNTHIAN_DIR:$ZYNTHIAN_UI_DIR${PYTHONPATH:+:$PYTHONPATH}"
export PATH="$ZYNTHIAN_DIR/bin:$ZYNTHIAN_DIR/venv/bin:$PATH"
export LV2_PATH="${LV2_PATH:-$HOME/.lv2:/usr/local/lib/lv2:/usr/lib/lv2:/usr/lib/x86_64-linux-gnu/lv2}"
export ZYNTHIAN_WIRING_LAYOUT=TOUCH_ONLY
export ZYNTHIAN_UI_TOUCH_NAVIGATION2=v5_keypad_left
export ZYNTHIAN_UI_ENABLE_CURSOR=1
export ZYNTHIAN_UI_FULLSCREEN="${ZYNTHIAN_UI_FULLSCREEN:-1}"
export ZYNTHIAN_UI_FONT_SIZE="${ZYNTHIAN_UI_FONT_SIZE:-22}"
export DISPLAY_WIDTH="${DISPLAY_WIDTH:-1280}"
export DISPLAY_HEIGHT="${DISPLAY_HEIGHT:-800}"
export ZYNTHIAN_UI_POWER_SAVE_MINUTES=0
export ZYNTHIAN_UI_RESTORE_LAST_STATE=1
export ZYNTHIAN_HOTPLUG_AUDIO=0
export ZYNTHIAN_MIDI_RTPMIDI_ENABLED=0
export ZYNTHIAN_MIDI_NETWORK_ENABLED=0
export ZYNTHIAN_MIDI_TOUCHOSC_ENABLED=0
export ZYNTHIAN_VNCSERVER_ENABLED=0
export ZYNTHIAN_LOG_LEVEL="${ZYNTHIAN_LOG_LEVEL:-20}"
export RBPI_VERSION_NUMBER=0
export RBPI_VERSION='Steam Deck x86_64'
export JACKD_OPTIONS='-d alsa -d hw:0 -r 48000 -p 256 -n 2'
export PYTHONUNBUFFERED=1
